import { useEffect, useState } from 'react'
import ReactMarkdown from 'react-markdown'
import remarkGfm from 'remark-gfm'
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog'
import { getStudySessionSummary, type StudySummary } from '@/lib/study'

interface SummaryDialogProps {
  open: boolean
  sessionId: string
  onClose: () => void
}

type SummaryState =
  | { status: 'loading' }
  | { status: 'error'; message: string }
  | { status: 'ready'; summary: StudySummary }

// The summary is untrusted LLM output: react-markdown never renders raw HTML,
// links are flattened to their text so nothing in it is clickable, and images
// are replaced by their alt text so opening the dialog never calls a remote
// host (a poisoned summary could otherwise carry conversation data in a URL).
const SUMMARY_COMPONENTS = {
  a: ({ children }: { children?: React.ReactNode }) => <span>{children}</span>,
  img: ({ alt }: { alt?: string }) => <span>{alt}</span>,
}

// Mounted only while the dialog is open, so every opening reads the current
// summary and a closed dialog holds none.
function SummaryBody({ sessionId }: { sessionId: string }) {
  const [state, setState] = useState<SummaryState>({ status: 'loading' })

  useEffect(() => {
    let cancelled = false
    getStudySessionSummary(sessionId)
      .then((summary) => {
        if (!cancelled) setState({ status: 'ready', summary })
      })
      .catch((err: unknown) => {
        if (cancelled) return
        setState({
          status: 'error',
          message: err instanceof Error ? err.message : 'Failed to load the summary.',
        })
      })
    return () => {
      cancelled = true
    }
  }, [sessionId])

  if (state.status === 'loading') {
    return <p className="text-sm text-muted-foreground">Loading summary…</p>
  }
  if (state.status === 'error') {
    return <p className="text-sm text-destructive">{state.message}</p>
  }
  if (!state.summary.found) {
    return <p className="text-sm text-muted-foreground">This session has no summary yet.</p>
  }
  return (
    <div className="thin-scroll max-h-[60vh] space-y-2 overflow-y-auto pr-2 text-sm [&_h2]:mt-3 [&_h2]:font-semibold [&_ul]:list-disc [&_ul]:pl-5">
      <ReactMarkdown remarkPlugins={[remarkGfm]} components={SUMMARY_COMPONENTS}>
        {state.summary.content}
      </ReactMarkdown>
    </div>
  )
}

// Read-only view of what Athena remembers of the older messages. Editing is
// out of scope (see specs/phases/phase-02-knowledge-engine/28-compaction-ux.md).
function SummaryDialog({ open, sessionId, onClose }: SummaryDialogProps) {
  return (
    <Dialog open={open} onOpenChange={(next) => !next && onClose()}>
      <DialogContent>
        <DialogHeader>
          <DialogTitle>Conversation summary</DialogTitle>
          <DialogDescription>
            Generated by the model from the older messages. It may contain mistakes and is never
            used as a source.
          </DialogDescription>
        </DialogHeader>
        <SummaryBody sessionId={sessionId} />
      </DialogContent>
    </Dialog>
  )
}

export { SummaryDialog }
